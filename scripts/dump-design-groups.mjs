// Snapshot a project's design groups (program + boards + answers) into a seed fixture.
//
//   node scripts/dump-design-groups.mjs [--project public-health] [--groups "Group 1,Group 2"]
//
// Writes data/design-groups.seed.json, which scripts/seed-design-groups.mjs replays onto a
// dev database. Reads from NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY (.env.local),
// or from SOURCE_SUPABASE_URL + SOURCE_SUPABASE_SERVICE_ROLE_KEY when set (e.g. to snapshot
// prod). Read-only against the source. --groups keeps only groups whose name starts with
// one of the comma-separated prefixes.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createClient } from "@supabase/supabase-js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const OUT = "data/design-groups.seed.json";

function loadEnv() {
  for (const file of [".env", ".env.local"]) {
    let raw;
    try {
      raw = readFileSync(join(root, file), "utf8");
    } catch {
      continue;
    }
    for (const line of raw.split("\n")) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (!m) continue;
      process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
}
loadEnv();

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : fallback;
}
const slug = arg("project", "public-health");
const prefixes = (arg("groups", "") || "").split(",").map((s) => s.trim()).filter(Boolean);

const URL = process.env.SOURCE_SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
const KEY = process.env.SOURCE_SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!URL || !KEY) {
  console.error("Missing Supabase env (NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY).");
  process.exit(1);
}
const sb = createClient(URL, KEY, { auth: { persistSession: false, autoRefreshToken: false } });

async function q(builder) {
  const { data, error } = await builder;
  if (error) throw error;
  return data;
}

async function main() {
  const [project] = await q(sb.from("projects").select("*").eq("slug", slug));
  if (!project) throw new Error(`Project "${slug}" not found.`);

  let groups = await q(
    sb.from("design_groups").select("*").eq("project_id", project.id).order("sort").order("created_at")
  );
  if (prefixes.length) groups = groups.filter((g) => prefixes.some((p) => g.name.startsWith(p)));
  if (groups.length === 0) throw new Error("No design groups matched.");

  const outGroups = [];
  let program = null;
  for (const g of groups) {
    const exercises = await q(
      sb.from("design_group_exercises").select("*").eq("group_id", g.id).order("sort").order("created_at")
    );
    // Every group runs the same program; the first group's weeks define it.
    program ??= exercises.map((e) => ({
      title: e.title,
      type: e.type,
      locked: e.locked,
      closed: e.closed,
      opensAt: e.opens_at,
      sections: e.sections,
      board: Boolean(e.session_code),
    }));

    const codes = exercises.map((e) => e.session_code).filter(Boolean);
    const sessions = codes.length ? await q(sb.from("sessions").select("code, config").in("code", codes)) : [];
    const players = codes.length
      ? await q(sb.from("ripple_players").select("id, display_name").in("code", codes))
      : [];
    const names = new Map(players.map((p) => [p.id, p.display_name]));

    const cards = [];
    for (const [week, e] of exercises.entries()) {
      if (!e.session_code) continue;
      const rows = await q(
        sb.from("ripple_cards").select("*").eq("code", e.session_code).order("created_at")
      );
      for (const c of rows)
        cards.push({
          id: c.id,
          week,
          order: c.card_order,
          parentId: c.parent_card_id,
          section: c.section,
          text: c.text,
          sort: c.sort,
          author: names.get(c.author_player_id) ?? null,
          sourceCardId: c.source_card_id ?? null,
          sourceLabel: c.source_label ?? null,
          createdAt: c.created_at,
        });
    }

    // Scenario snapshot shared by the group's boards (premise, resolutions, flags).
    const firstBoard = exercises.find((e) => e.session_code);
    const boardConfig = sessions.find((s) => s.code === firstBoard?.session_code)?.config ?? {};

    outGroups.push({
      name: g.name,
      sort: g.sort,
      color: g.color,
      scenarioRef: g.scenario_ref,
      scenarioSetId: g.scenario_set_id,
      scenarioTitle: g.scenario_title,
      boardConfig,
      cards,
    });
  }

  const fixture = {
    _about:
      "Design-group seed fixture. Generated by scripts/dump-design-groups.mjs; replayed by scripts/seed-design-groups.mjs.",
    exportedAt: new Date().toISOString(),
    project: {
      slug: project.slug,
      name: project.name,
      carmelitaProjectRef: project.carmelita_project_ref,
      homeConfig: project.home_config,
    },
    program,
    groups: outGroups,
  };
  writeFileSync(join(root, OUT), JSON.stringify(fixture, null, 2) + "\n");
  const total = outGroups.reduce((n, g) => n + g.cards.length, 0);
  console.log(`✓ ${OUT}: ${outGroups.length} groups, ${program.length} weeks, ${total} cards`);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
